#!/usr/bin/env python3
"""Re-measure everything and rewrite docs/MEASUREMENTS.md.

    python3 tools/write_measurements.py      (after scripts/test.sh)
"""
import pathlib
import re
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
A = str(ROOT / "build/tests/analyze")
PEDALS = ["rat", "ts808", "ds1", "bd2", "mt2"]


def sh(*cmd):
    return subprocess.run(cmd, check=True, capture_output=True, text=True, cwd=ROOT).stdout


subprocess.run(["bash", "scripts/build.sh", "native"], check=True, capture_output=True, cwd=ROOT)
sections, cpu = [], {}
for p in PEDALS:
    so = f"build/native/pfx-{p}/pfx-{p}.so"
    out = ROOT / "build/analysis" / p
    out.mkdir(parents=True, exist_ok=True)
    table = sh(A, so, str(out), "all")
    c = sh(A, so, "x", "cpu")
    presets = sh(A, so, "x", "presets")
    cpu[p] = [float(x) for x in re.findall(r": ([0-9.]+) us", c)]
    sections.append(f"### {p}\n\n```\n{table}{c}```\n\nPresets (loudness on the pluck phrase, THD at 220 Hz):\n\n```\n{presets}```\n")
sweep = sh("bash", "tools/os_sweep.sh")
os_factor = {p: __import__("json").loads((ROOT / f"src/{p}/pedal.json").read_text())["oversampling"] for p in PEDALS}
rows = []
tot = [0.0, 0.0]
for p in PEDALS:
    st, mo = cpu[p]
    tot[0] += st
    tot[1] += mo
    rows.append(f"| {p} ({os_factor[p]}x) | {st:.1f} / {mo:.1f} | {4*st:.0f}-{7*st:.0f} | {100*4*st/2902:.1f}-{100*7*st/2902:.1f} % |")
rows.append(f"| all five | {tot[0]:.0f} / {tot[1]:.0f} | {4*tot[0]:.0f}-{7*tot[0]:.0f} | {100*4*tot[0]/2902:.0f}-{100*7*tot[0]/2902:.0f} % |")

doc = f"""# Measurements (host)

Generated by `tools/write_measurements.py`: every number comes from
`tools/analyze` / `tools/os_sweep.sh` through the real `.so` and the v2 ABI
(int16 in/out, 128-frame blocks, 44.1 kHz). Host: AMD Ryzen 5 5600 (Zen 3),
gcc -O2, one thread.

## Drive sweep per pedal (defaults, knob 1 = 0.25 / 0.5 / 0.75 / 1.0)

- `pluckdB`: output / input RMS of a plucked-string phrase peaking at -6 dBFS
  (0 dB at the default knob settings is the level calibration)
- `THD110`, `THD1k`: THD of a -12 dBFS sine; `H2/H1`, `H3/H1`: 2nd / 3rd
  harmonic vs fundamental at 1 kHz; `even/odd`: energy of all even vs all odd
  harmonics (asymmetry)
- `alias1k`, `alias5k`: energy that is not a harmonic (aliasing plus
  rounding) relative to the harmonic energy, steady 1 kHz / 5 kHz sine
- `cpu`: microseconds per 128-frame block, hot noise, Drive moving;
  "stereo" = independent L/R (worst case), "mono" = L == R (processed once)
- WAVs of the sweep: `build/analysis/<pedal>/drive_025|050|075|100.wav`
  (pluck phrase, 110 Hz, 1 kHz, then a 20 Hz-20 kHz sweep)

{chr(10).join(sections)}
## Oversampling: 1x / 2x / 4x

`a1k@.5` = alias floor at 1 kHz with knob 1 at 0.5, etc.; `us/block` = stereo
worst case.

```
{sweep}```

Shipped factors:

| pedal | factor | reason |
|---|---|---|
| RAT | **4x** | the op-amp filter runs at the base rate, so 4x costs ~+1 us over 2x and buys ~20 dB at 1 kHz |
| TS808 | 2x | 1x leaves the 5 kHz floor at -15 dB; 4x costs +50 % for floors already below -68 dB at 1 kHz |
| DS-1 | **4x** | hardest clipping of the set: at defaults 2x = -39 dB, 4x = -60 dB (1 kHz), for +30 % CPU |
| BD-2 | 2x | -80 dB at defaults already; 4x only helps at full gain |
| MT-2 | **4x** | (v0.3; was 2x as first specified) at full Distortion 2x left non-harmonic energy at -29 dB (1 kHz) / -32 dB (5 kHz); 4x gives -35 / -70 dB for ~+35 % CPU |

The half-band pair itself (up + down, both channels) costs about 5 us per
stereo block at 2x; the rest of the oversampled cost is the nonlinear stages
running at the higher rate. First-order ADAA on the rail limiters was tried
on BD-2: 2x + ADAA reached plain 4x's alias floor but was slower (50.6 vs
41.1 us, double-precision log1p), so it was not kept.

## Circuit cross-check (tests/test_common.c)

The TS808 feedback clipper and the DS-1 RC-diode clipper as implemented
(float, closed-form diode solve, oversampled) against a double-precision solve
of the same circuit ODE at 16x with Newton iterated to 1e-12: every harmonic
within 50 dB of the fundamental agrees within 1 dB (TS808, typically < 0.3 dB)
and 0.1 dB (DS-1). The closed-form diode solve is within 2 mV (single
diodes) / 4 mV (two in series) of the exact solution over 0-10 V drive.

The RAT port reproduces dm-Rat's own unit-test coefficient vectors to 1e-5
relative; its op-amp filter peaks at +66.5 dB (dm-Rat: 67.26 dB maximum
distortion gain; the gap is bilinear warping near 4.7 kHz).

## CPU on the Move — estimate, to be confirmed on the device

Not measured on ARM (no SSH to the Move, no ARM64 machine here). A Cortex-A72
at 1.5 GHz runs scalar single-threaded code roughly 4-7x slower than this
Zen 3 core. Per instance, host stereo / mono, and the Move estimate (stereo):

| pedal | host us/block | Move estimate us/block | of the 2902 us block |
|---|---|---|---|
{chr(10).join(rows)}

Check on the device: Schwung Manager -> System -> CPU (`/system/cpu`).
"""
(ROOT / "docs/MEASUREMENTS.md").write_text(doc)
print(doc.split("## CPU on the Move")[1])
